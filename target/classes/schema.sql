create table if not exists members (
    id BIGINT generated by default as identity primary key,
    member_no VARCHAR(30) not null unique,
    name VARCHAR(80) not null,
    phone VARCHAR(30),
    email VARCHAR(120),
    status VARCHAR(20) not null default 'ACTIVE',
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP,
    updated_at TIMESTAMP not null default CURRENT_TIMESTAMP
);

create index if not exists idx_members_name onmembers(name);

create index if not exists idx_members_phone onmembers(phone);

create table if not exists golf_courses (
    id BIGINT generated by default as identity primary key,
    course_code VARCHAR(30) not null unique,
    name VARCHAR(80) not null,
    hole_count INT not null default 18,
    status VARCHAR(20) not null default 'OPEN',
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP,
    updated_at TIMESTAMP not null default CURRENT_TIMESTAMP
);

create table if not exists reservations (
    id BIGINT generated by default as identity primary key,
    reservation_no VARCHAR(30) not null unique,
    member_id BIGINT not null,
    course_id BIGINT not null,
    reserved_at TIMESTAMP not null,
    player_count INT not null default 4,
    status VARCHAR(20) not null default 'PENDING',
    memo VARCHAR(500),
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP,
    updated_at TIMESTAMP not null default CURRENT_TIMESTAMP,
    constraint fk_res_member foreign key(member_id) references members(id),
    constraint fk_res_course foreign key(course_id) references golf_courses(id)
);

create index if not exists idx_res_reserved_at on reservations(reserved_at);

create index if not exists idx_res_status_reserved on reservations(status, reserved_at);

create table if not exists fee_policies (
    id BIGINT generated by default as identity primary key,
    name VARCHAR(80) not null,
    day_type VARCHAR(20) not null,
    start_time TIME not null,
    end_time TIME not null,
    amount DECIMAL(12, 2) not null,
    active BOOLEAN not null default true,
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP
);

create table if not exists payments (
    id BIGINT generated by default as identity primary key,
    reservation_id BIGINT not null,
    amount DECIMAL(12, 2) not null,
    status VARCHAR(20) not null default 'READY',
    paid_at TIMESTAMP null,
    payment_method VARCHAR(30),
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP,
    constraint fk_payment_res foreign key(reservation_id) references reservations(id)
);

create table if not exists settlements (
    id BIGINT generated by default as identity primary key,
    settlement_date DATE not null unique,
    gross_amount DECIMAL(14, 2) not null default 0,
    refund_amount DECIMAL(14, 2) not null default 0,
    net_amount DECIMAL(14, 2) not null default 0,
    status VARCHAR(20) not null default 'OPEN',
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP
);

create table if not exists users (
    id BIGINT generated by default as identity primary key,
    username VARCHAR(60) not null unique,
    password_hash VARCHAR(255) not null,
    display_name VARCHAR(80) not null,
    role VARCHAR(30) not null default 'STAFF',
    active BOOLEAN not null default true,
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP
);

create table if not exists audit_logs (
    id BIGINT generated by default as identity primary key,
    actor_username VARCHAR(60),
    action VARCHAR(80) not null,
    entity_type VARCHAR(80) not null,
    entity_id BIGINT,
    details JSON,
    created_at TIMESTAMP not null default CURRENT_TIMESTAMP
);