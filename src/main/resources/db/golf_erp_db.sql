-- =====================================================================
-- 골프장 통합 스키마 (PostgreSQL, schema: golf) — 예약 + ERP
--
--   1부. 공용·예약 영역 : golf-reservation-api 의 schema.sql 과 같다.
--   2부. ERP 영역       : golf-erp-api 가 쓰는 테이블(코스·홀·캐디·카트·
--                         라운드·스코어·이용 내역·요금·수납·일 마감).
--
--   모든 문장은 IF NOT EXISTS 라 여러 번 실행해도 안전하다(기존 데이터 유지).
--   Spring sql.init(dev) 로 실행되므로 BEGIN/COMMIT, SET search_path 는 쓰지 않는다.
--   psql 로 한 번에 실행: psql -1 -h localhost -U postgres -d golf -f schema.sql
-- =====================================================================

-- =====================================================================
-- 골프장 예약 시스템 통합 스키마 (PostgreSQL, schema: golf)
--
--   M: 이전 통합 스키마 (members, users, golf_courses, tee_times,
--      fee_policies, reservations, payments, settlements, audit_logs)
--   G: golf 스키마     (member, golf_course, green_fee_policy, tee_time,
--      reservation, reservation_player, reservation_history,
--      golf_course_closure, payment, reservation_restriction)
--
-- 통합 원칙
--   1. 명명 규칙은 G 를 따른다: 단수형 테이블명, PK 는 <테이블>_id,
--      의미가 겹치는 컬럼은 접두어를 붙인 G 의 이름(member_name 등).
--   2. 같은 테이블은 양쪽 컬럼을 모두 포함(합집합)한다.
--      이름만 다르고 의미가 같은 컬럼은 G 의 이름으로 하나로 합친다.
--   3. 한쪽에만 있는 컬럼은 NULL 허용 또는 DEFAULT 를 두어
--      다른 쪽 애플리케이션의 INSERT 가 실패하지 않게 한다.
--   4. 길이·정밀도·정수 타입이 다르면 더 넓은 쪽을 택한다.
--   5. 상태값 CHECK 는 양쪽 값의 합집합으로 만든다.
--   6. 시각 기본값은 LOCALTIMESTAMP, 정밀도는 TIMESTAMP(6) 으로 맞춘다.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS golf;

SET search_path TO golf;

BEGIN;

/* ---------------------------------------------------------------------
 * 1. 회원 (M.members + G.member)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.member (
    member_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_no     VARCHAR(30),                                 -- [M] 회원번호
    login_id      VARCHAR(100),                                -- [G] NOT NULL -> 오프라인 회원 위해 NULL 허용
    password_hash VARCHAR(255),                                -- BCrypt, 오프라인 회원은 NULL
    member_name   VARCHAR(100) NOT NULL,                       -- M.name
    phone         VARCHAR(30),
    email         VARCHAR(255),                                -- 소문자로 정규화해 저장
    role          VARCHAR(10)  NOT NULL DEFAULT 'USER',        -- [M]
    member_status VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',      -- M.status
    created_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_member PRIMARY KEY (member_id),
    CONSTRAINT uq_member_login_id  UNIQUE (login_id),          -- NULL 은 중복 허용
    CONSTRAINT uq_member_member_no UNIQUE (member_no),
    CONSTRAINT uq_member_email     UNIQUE (email),
    CONSTRAINT ck_member_role   CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_member_status CHECK (member_status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE INDEX IF NOT EXISTS ix_member_name  ON golf.member (member_name);
CREATE INDEX IF NOT EXISTS ix_member_phone ON golf.member (phone);


/* ---------------------------------------------------------------------
 * 2. 관리자/직원 계정 (M.users)
 *    USER 는 PostgreSQL 예약어라 admin_user 로 이름을 바꾼다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.admin_user (
    admin_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(60)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    role          VARCHAR(30)  NOT NULL DEFAULT 'STAFF',
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,          -- M.active
    created_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_admin_user PRIMARY KEY (admin_user_id),
    CONSTRAINT uq_admin_user_username UNIQUE (username)
);


/* ---------------------------------------------------------------------
 * 3. 골프장 (M.golf_courses + G.golf_course)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.golf_course (
    golf_course_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    course_code    VARCHAR(30)  NOT NULL,
    course_name    VARCHAR(200) NOT NULL,                      -- M.name
    address        VARCHAR(500),                               -- [G]
    phone          VARCHAR(30),                                -- [G]
    hole_count     INTEGER      DEFAULT 18,                    -- M INTEGER NOT NULL / G SMALLINT NULL
    course_status  VARCHAR(20)  NOT NULL DEFAULT 'OPEN',       -- M.status
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,         -- [G]
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP, -- [M]
    CONSTRAINT pk_golf_course PRIMARY KEY (golf_course_id),
    CONSTRAINT uq_golf_course_code UNIQUE (course_code)
);


/* ---------------------------------------------------------------------
 * 4. 골프장 휴장 관리 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.golf_course_closure (
    closure_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id BIGINT       NOT NULL,
    closure_start  TIMESTAMP(6) NOT NULL,                      -- 포함
    closure_end    TIMESTAMP(6) NOT NULL,                      -- 미포함
    closure_type   VARCHAR(20)  NOT NULL DEFAULT 'CLOSED',
    reason         VARCHAR(500) NOT NULL,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_golf_course_closure PRIMARY KEY (closure_id),
    CONSTRAINT fk_closure_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_closure_period CHECK (closure_end > closure_start)
);

CREATE INDEX IF NOT EXISTS ix_closure_course_period
    ON golf.golf_course_closure (golf_course_id, closure_start, closure_end);


/* ---------------------------------------------------------------------
 * 5. 그린피 요금 정책 (M.fee_policies + G.green_fee_policy)
 *    M 은 골프장·유효기간 개념이 없으므로
 *    golf_course_id 는 NULL 허용(NULL = 전체 골프장),
 *    유효기간은 DEFAULT 로 '무기한' 을 채운다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.green_fee_policy (
    green_fee_policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id      BIGINT,                                -- [G] NOT NULL -> NULL 허용
    policy_name         VARCHAR(150)  NOT NULL,                -- M.name
    valid_from          DATE          NOT NULL DEFAULT CURRENT_DATE,
    valid_to            DATE          NOT NULL DEFAULT DATE '9999-12-31',
    day_type            VARCHAR(20),                           -- [M] 예: WEEKDAY, WEEKEND, HOLIDAY
    day_of_week         SMALLINT,                              -- [G] 1(월)~7(일), NULL 이면 모든 요일
    time_from           TIME,                                  -- M.start_time, 포함. NULL 이면 제한 없음
    time_to             TIME,                                  -- M.end_time, 미포함. NULL 이면 제한 없음
    base_fee            NUMERIC(12,2) NOT NULL,                -- M.amount
    discount_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE,   -- M.active
    created_at          TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_green_fee_policy PRIMARY KEY (green_fee_policy_id),
    CONSTRAINT fk_green_fee_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_green_fee_dates CHECK (valid_to >= valid_from),
    CONSTRAINT ck_green_fee_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_green_fee_amount
        CHECK (base_fee >= 0 AND discount_amount >= 0 AND discount_amount <= base_fee)
);

CREATE INDEX IF NOT EXISTS ix_green_fee_course_valid
    ON golf.green_fee_policy (golf_course_id, valid_from, valid_to);


/* ---------------------------------------------------------------------
 * 6. 티타임 (M.tee_times + G.tee_time)
 *    M 은 course(OUT/IN 같은 세부 코스) 로, G 는 golf_course_id 로 슬롯을 구분한다.
 *    두 방식을 함께 지키도록 슬롯 유일성은 식 인덱스(ux_tee_time_slot)로 건다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.tee_time (
    tee_time_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id  BIGINT,                                    -- [G] NOT NULL -> NULL 허용 (M.course_id)
    course          VARCHAR(20),                               -- [M] 세부 코스, 예: OUT, IN
    play_date       DATE          NOT NULL,
    start_time      TIME          NOT NULL,                    -- M TIME(0) / G TIME -> TIME
    hole_type       VARCHAR(10)   NOT NULL DEFAULT '18H',      -- [G]
    capacity        SMALLINT      NOT NULL DEFAULT 4,          -- [G]
    green_fee       NUMERIC(12,2),                             -- [M] 1인 그린피(원)
    tee_time_status VARCHAR(20)   NOT NULL DEFAULT 'OPEN',     -- M.status
    version         BIGINT        NOT NULL DEFAULT 0,          -- [M] 낙관적 잠금(@Version)
    CONSTRAINT pk_tee_time PRIMARY KEY (tee_time_id),
    CONSTRAINT fk_tee_time_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_tee_time_slot CHECK (golf_course_id IS NOT NULL OR course IS NOT NULL),
    CONSTRAINT ck_tee_time_capacity CHECK (capacity BETWEEN 1 AND 8),
    CONSTRAINT ck_tee_time_status
        CHECK (tee_time_status IN ('OPEN', 'BOOKED', 'BLOCKED', 'CLOSED'))
);

-- G 의 (골프장, 날짜, 시각) 과 M 의 (날짜, 시각, 코스) 유일성을 하나로 합친 것
CREATE UNIQUE INDEX IF NOT EXISTS ux_tee_time_slot
    ON golf.tee_time (COALESCE(golf_course_id, 0), play_date, start_time, COALESCE(course, ''));

-- [G] 티타임 조회 성능
CREATE INDEX IF NOT EXISTS ix_tee_time_search
    ON golf.tee_time (golf_course_id, play_date, tee_time_status, start_time);

-- [M] 골프장 없이 날짜별로 조회하는 경우
CREATE INDEX IF NOT EXISTS ix_tee_time_play_date
    ON golf.tee_time (play_date, start_time);


/* ---------------------------------------------------------------------
 * 7. 예약 (M.reservations + G.reservation)
 *    주의: reserved_at 의 의미가 서로 다르다.
 *      G.reserved_at = 예약한 시각  -> 그대로 reserved_at
 *      M.reserved_at = 플레이 일시  -> play_at 으로 이름 변경
 *    슬롯은 tee_time_id 또는 (golf_course_id + play_at) 중 하나가 있어야 한다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation (
    reservation_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_no     VARCHAR(30),                            -- [G] NOT NULL -> NULL 허용
    member_id          BIGINT        NOT NULL,
    tee_time_id        BIGINT,                                 -- [G] NOT NULL -> NULL 허용
    golf_course_id     BIGINT,                                 -- M.course_id
    play_at            TIMESTAMP(6),                           -- M.reserved_at (플레이 일시)
    reservation_status VARCHAR(20)   NOT NULL DEFAULT 'PENDING', -- M.status
    player_count       INTEGER       NOT NULL DEFAULT 4,
    green_fee_amount   NUMERIC(12,2),                          -- [G] NOT NULL -> NULL 허용
    discount_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,       -- [G]
    total_amount       NUMERIC(12,2),                          -- 그린피 × 인원 - 할인(원)
    memo               VARCHAR(500),                           -- [M]
    reserved_at        TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP, -- [G] 예약한 시각
    created_at         TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP, -- [M]
    updated_at         TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP, -- [M]
    payment_started_at TIMESTAMP(6),                           -- [M] 마지막으로 PAYING 에 들어간 시각
    confirmed_at       TIMESTAMP(6),
    cancelled_at       TIMESTAMP(6),
    cancel_reason      VARCHAR(500),                           -- M 200 / G 500 -> 500
    version            BIGINT        NOT NULL DEFAULT 0,       -- [M] 낙관적 잠금(@Version)
    CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),
    CONSTRAINT uq_reservation_no UNIQUE (reservation_no),
    CONSTRAINT fk_reservation_member   FOREIGN KEY (member_id)      REFERENCES golf.member (member_id),
    CONSTRAINT fk_reservation_tee_time FOREIGN KEY (tee_time_id)    REFERENCES golf.tee_time (tee_time_id),
    CONSTRAINT fk_reservation_course   FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_reservation_slot
        CHECK (tee_time_id IS NOT NULL OR (golf_course_id IS NOT NULL AND play_at IS NOT NULL)),
    CONSTRAINT ck_reservation_player_count CHECK (player_count BETWEEN 1 AND 8),  -- 티타임 capacity 상한과 맞춤
    CONSTRAINT ck_reservation_status
        CHECK (reservation_status IN (
            'PENDING', 'PENDING_PAYMENT', 'PAYING', 'CONFIRMED', 'REFUND_PENDING',
            'CANCELLED', 'COMPLETED', 'NO_SHOW', 'FAILED')),
    CONSTRAINT ck_reservation_amount
        CHECK (green_fee_amount >= 0
               AND discount_amount >= 0
               AND total_amount >= 0
               AND discount_amount <= green_fee_amount)
);

-- [G] 활성 예약은 티타임당 최대 1건 (ReservationStatus.ACTIVE_STATUSES 와 같은 조건)
--     M 의 결제 진행 상태(PENDING_PAYMENT, PAYING)도 슬롯을 점유하므로 포함
CREATE UNIQUE INDEX IF NOT EXISTS ux_reservation_active_tee_time
    ON golf.reservation (tee_time_id)
    WHERE reservation_status IN ('PENDING', 'PENDING_PAYMENT', 'PAYING', 'CONFIRMED');

-- [G] 회원별 최근 예약
CREATE INDEX IF NOT EXISTS ix_reservation_member
    ON golf.reservation (member_id, reserved_at DESC);
-- [M] 내 예약 목록, 회원별 미결제 예약 수
CREATE INDEX IF NOT EXISTS ix_reservation_member_status
    ON golf.reservation (member_id, reservation_status);
-- [M] 티타임 조인, 예약 이력 확인 (부분 인덱스는 활성 예약만 담으므로 별도로 둔다)
CREATE INDEX IF NOT EXISTS ix_reservation_tee_time
    ON golf.reservation (tee_time_id);
-- [M] 골프장 외래 키 (PostgreSQL 은 FK 인덱스를 자동 생성하지 않음)
CREATE INDEX IF NOT EXISTS ix_reservation_course
    ON golf.reservation (golf_course_id);
-- [M] 플레이 일시별 조회, 상태+플레이 일시 조회
CREATE INDEX IF NOT EXISTS ix_reservation_play_at
    ON golf.reservation (play_at);
CREATE INDEX IF NOT EXISTS ix_reservation_status_play_at
    ON golf.reservation (reservation_status, play_at);
-- [M] 결제 대기 자동 취소 작업
CREATE INDEX IF NOT EXISTS ix_reservation_status_created
    ON golf.reservation (reservation_status, created_at);
-- [M] 오래 멈춘 결제 감지
CREATE INDEX IF NOT EXISTS ix_reservation_status_payment_started
    ON golf.reservation (reservation_status, payment_started_at);


/* ---------------------------------------------------------------------
 * 8. 예약자 및 동반자 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation_player (
    reservation_player_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id        BIGINT       NOT NULL,
    player_order          SMALLINT     NOT NULL,
    player_name           VARCHAR(100) NOT NULL,
    phone                 VARCHAR(30),
    member_id             BIGINT,
    is_booking_member     BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_reservation_player PRIMARY KEY (reservation_player_id),
    CONSTRAINT fk_player_reservation FOREIGN KEY (reservation_id) REFERENCES golf.reservation (reservation_id),
    CONSTRAINT fk_player_member      FOREIGN KEY (member_id)      REFERENCES golf.member (member_id),
    CONSTRAINT uq_player_order UNIQUE (reservation_id, player_order)
);

CREATE INDEX IF NOT EXISTS ix_player_member ON golf.reservation_player (member_id);


/* ---------------------------------------------------------------------
 * 9. 예약 변경 이력 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation_history (
    reservation_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id         BIGINT        NOT NULL,
    action_type            VARCHAR(30)   NOT NULL,
    before_status          VARCHAR(20),
    after_status           VARCHAR(20),
    before_tee_time_id     BIGINT,
    after_tee_time_id      BIGINT,
    before_amount          NUMERIC(12,2),
    after_amount           NUMERIC(12,2),
    reason                 VARCHAR(1000),
    actor_member_id        BIGINT,
    created_at             TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_reservation_history PRIMARY KEY (reservation_history_id),
    CONSTRAINT fk_history_reservation FOREIGN KEY (reservation_id)  REFERENCES golf.reservation (reservation_id),
    CONSTRAINT fk_history_actor       FOREIGN KEY (actor_member_id) REFERENCES golf.member (member_id)
);

CREATE INDEX IF NOT EXISTS ix_history_reservation
    ON golf.reservation_history (reservation_id, created_at);


/* ---------------------------------------------------------------------
 * 10. 회원별 예약 제한 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation_restriction (
    restriction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_id        BIGINT        NOT NULL,
    restriction_type VARCHAR(30)   NOT NULL,
    starts_at        TIMESTAMP(6)  NOT NULL,
    ends_at          TIMESTAMP(6),                             -- NULL 이면 무기한
    reason           VARCHAR(1000) NOT NULL,
    created_by       BIGINT,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_reservation_restriction PRIMARY KEY (restriction_id),
    CONSTRAINT fk_restriction_member FOREIGN KEY (member_id) REFERENCES golf.member (member_id),
    CONSTRAINT ck_restriction_period CHECK (ends_at IS NULL OR ends_at > starts_at)
);

CREATE INDEX IF NOT EXISTS ix_restriction_member
    ON golf.reservation_restriction (member_id, starts_at);


/* ---------------------------------------------------------------------
 * 11. 결제 및 환불 (M.payments + G.payment)
 *     G 는 환불을 별도 행(payment_type = 'REFUND')으로 남기므로
 *     M 의 "예약당 1건" UNIQUE 는 제거하고 일반 인덱스로 둔다.
 *     M 은 한 행에서 refunded_at 으로 환불을 표시한다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.payment (
    payment_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id    BIGINT        NOT NULL,
    payment_type      VARCHAR(20)   NOT NULL DEFAULT 'PAYMENT', -- [G]
    payment_status    VARCHAR(20)   NOT NULL DEFAULT 'READY',   -- M.status
    payment_method    VARCHAR(30),                              -- M.method
    pg_provider       VARCHAR(50),                              -- [G]
    pg_transaction_id VARCHAR(200),                             -- M.transaction_id
    amount            NUMERIC(12,2) NOT NULL,
    requested_at      TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP, -- M.created_at
    completed_at      TIMESTAMP(6),                             -- M.paid_at
    refunded_at       TIMESTAMP(6),                             -- [M]
    failure_reason    VARCHAR(500),                             -- [G]
    CONSTRAINT pk_payment PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_reservation FOREIGN KEY (reservation_id) REFERENCES golf.reservation (reservation_id),
    CONSTRAINT ck_payment_type CHECK (payment_type IN ('PAYMENT', 'REFUND')),
    CONSTRAINT ck_payment_status
        CHECK (payment_status IN (
            'READY', 'PENDING', 'SUCCEEDED', 'PAID',
            'FAILED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    -- [M] PAID 상태는 결제 시각과 PG 거래 번호가 있어야 한다
    CONSTRAINT ck_payment_paid
        CHECK (payment_status <> 'PAID' OR (completed_at IS NOT NULL AND pg_transaction_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ix_payment_reservation
    ON golf.payment (reservation_id, payment_type);


/* ---------------------------------------------------------------------
 * 12. 일별 정산 (M.settlements)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.settlement (
    settlement_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    settlement_date   DATE          NOT NULL,
    gross_amount      NUMERIC(14,2) NOT NULL DEFAULT 0,
    refund_amount     NUMERIC(14,2) NOT NULL DEFAULT 0,
    net_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    settlement_status VARCHAR(20)   NOT NULL DEFAULT 'OPEN',   -- M.status
    created_at        TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_settlement PRIMARY KEY (settlement_id),
    CONSTRAINT uq_settlement_date UNIQUE (settlement_date)
);


/* ---------------------------------------------------------------------
 * 13. 감사 로그 (M.audit_logs)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.audit_log (
    audit_log_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_username VARCHAR(60),
    action         VARCHAR(80)  NOT NULL,
    entity_type    VARCHAR(80)  NOT NULL,
    entity_id      BIGINT,
    details        JSONB,
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_log_id)
);

CREATE INDEX IF NOT EXISTS ix_audit_log_entity ON golf.audit_log (entity_type, entity_id);



-- #####################################################################
-- ERP 영역 (golf-erp-api)
--   예약 시스템(golf-reservation-api)과 같은 golf 스키마를 쓴다.
--   위의 공용 테이블(member, golf_course, tee_time, reservation, admin_user,
--   green_fee_policy, audit_log)을 참조하고, 아래 테이블을 새로 만든다.
--
--   [마스터]   course, hole, caddie, cart, service_fee
--   [라운드]   round, round_player, round_course, round_assignment,
--              score, round_event
--   [정산]     round_charge, round_payment, daily_settlement,
--              daily_settlement_item
--
--   용어: 골프장(golf_course) > 코스(course: OUT·IN 등 9홀 묶음) > 홀(hole)
--         라운드(round) = 한 팀이 체크인부터 종료까지 골프장을 이용한 한 번
-- #####################################################################


/* ---------------------------------------------------------------------
 * E-0. 직원 계정 확장 (admin_user)
 *      ERP 로그인 계정으로 쓴다. 역할: ADMIN, MANAGER, FRONT, STARTER,
 *      CADDIE_MASTER, STAFF (기존 행이 있을 수 있어 CHECK 는 두지 않는다)
 * ------------------------------------------------------------------- */
ALTER TABLE golf.admin_user ADD COLUMN IF NOT EXISTS phone         VARCHAR(30);
ALTER TABLE golf.admin_user ADD COLUMN IF NOT EXISTS department    VARCHAR(50);
ALTER TABLE golf.admin_user ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMP(6);
ALTER TABLE golf.admin_user ADD COLUMN IF NOT EXISTS updated_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP;


/* ---------------------------------------------------------------------
 * E-1. 코스 (골프장 안의 9홀 단위 코스: OUT, IN, EAST ...)
 *      course_code 는 tee_time.course 와 같은 값을 쓴다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.course (
    course_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id BIGINT       NOT NULL,
    course_code    VARCHAR(20)  NOT NULL,
    course_name    VARCHAR(100) NOT NULL,
    hole_count     SMALLINT     NOT NULL DEFAULT 9,
    sort_order     SMALLINT     NOT NULL DEFAULT 0,
    course_status  VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_course PRIMARY KEY (course_id),
    CONSTRAINT fk_course_golf_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT uq_course_code UNIQUE (golf_course_id, course_code),
    CONSTRAINT ck_course_hole_count CHECK (hole_count BETWEEN 1 AND 18),
    CONSTRAINT ck_course_status CHECK (course_status IN ('OPEN', 'MAINTENANCE', 'CLOSED'))
);


/* ---------------------------------------------------------------------
 * E-2. 홀 (파·핸디캡·거리)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.hole (
    hole_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    course_id        BIGINT       NOT NULL,
    hole_no          SMALLINT     NOT NULL,                  -- 코스 안 번호(1~)
    par              SMALLINT     NOT NULL,
    handicap         SMALLINT,                               -- 난이도 순위(1 = 가장 어려움)
    distance_back    INTEGER,                                -- 백티 거리(m)
    distance_regular INTEGER,                                -- 레귤러티 거리(m)
    distance_front   INTEGER,                                -- 레이디/프런트티 거리(m)
    memo             VARCHAR(500),
    created_at       TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at       TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_hole PRIMARY KEY (hole_id),
    CONSTRAINT fk_hole_course FOREIGN KEY (course_id) REFERENCES golf.course (course_id),
    CONSTRAINT uq_hole_no UNIQUE (course_id, hole_no),
    CONSTRAINT ck_hole_no CHECK (hole_no BETWEEN 1 AND 18),
    CONSTRAINT ck_hole_par CHECK (par BETWEEN 3 AND 6),
    CONSTRAINT ck_hole_handicap CHECK (handicap IS NULL OR handicap BETWEEN 1 AND 18),
    CONSTRAINT ck_hole_distance CHECK (
        (distance_back IS NULL OR distance_back > 0)
        AND (distance_regular IS NULL OR distance_regular > 0)
        AND (distance_front IS NULL OR distance_front > 0))
);


/* ---------------------------------------------------------------------
 * E-3. 캐디
 *      caddie_status 는 근무 상태다. 지금 라운드에 나가 있는지는
 *      round_assignment 의 미해제 배정으로 판단한다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.caddie (
    caddie_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id BIGINT       NOT NULL,
    caddie_no      VARCHAR(20)  NOT NULL,
    caddie_name    VARCHAR(100) NOT NULL,
    phone          VARCHAR(30),
    grade          VARCHAR(10),                              -- 예: A, B, C
    caddie_status  VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    hired_on       DATE,
    memo           VARCHAR(500),
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_caddie PRIMARY KEY (caddie_id),
    CONSTRAINT fk_caddie_golf_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT uq_caddie_no UNIQUE (golf_course_id, caddie_no),
    CONSTRAINT ck_caddie_status CHECK (caddie_status IN ('ACTIVE', 'ON_LEAVE', 'RETIRED'))
);


/* ---------------------------------------------------------------------
 * E-4. 카트
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.cart (
    cart_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id BIGINT       NOT NULL,
    cart_no        VARCHAR(20)  NOT NULL,
    seat_count     SMALLINT     NOT NULL DEFAULT 5,
    cart_status    VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    memo           VARCHAR(500),
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_cart PRIMARY KEY (cart_id),
    CONSTRAINT fk_cart_golf_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT uq_cart_no UNIQUE (golf_course_id, cart_no),
    CONSTRAINT ck_cart_seat_count CHECK (seat_count BETWEEN 1 AND 10),
    CONSTRAINT ck_cart_status CHECK (cart_status IN ('ACTIVE', 'MAINTENANCE', 'RETIRED'))
);


/* ---------------------------------------------------------------------
 * E-5. 부대 요금표 (카트비·캐디피·대여료 등)
 *      그린피는 tee_time.green_fee 또는 green_fee_policy 를 쓴다.
 *      hole_basis: 9 또는 18 (NULL 이면 홀 수와 무관)
 *      charge_unit: TEAM(팀당) / PLAYER(1인당)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.service_fee (
    service_fee_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id BIGINT        NOT NULL,
    fee_type       VARCHAR(20)   NOT NULL,
    fee_name       VARCHAR(100)  NOT NULL,
    charge_unit    VARCHAR(10)   NOT NULL DEFAULT 'TEAM',
    hole_basis     SMALLINT,
    amount         NUMERIC(12,2) NOT NULL,
    valid_from     DATE          NOT NULL DEFAULT CURRENT_DATE,
    valid_to       DATE          NOT NULL DEFAULT DATE '9999-12-31',
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_service_fee PRIMARY KEY (service_fee_id),
    CONSTRAINT fk_service_fee_golf_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_service_fee_type CHECK (fee_type IN ('CADDIE_FEE', 'CART_FEE', 'RENTAL', 'LOCKER', 'ETC')),
    CONSTRAINT ck_service_fee_unit CHECK (charge_unit IN ('TEAM', 'PLAYER')),
    CONSTRAINT ck_service_fee_hole_basis CHECK (hole_basis IS NULL OR hole_basis IN (9, 18, 27, 36)),
    CONSTRAINT ck_service_fee_amount CHECK (amount >= 0),
    CONSTRAINT ck_service_fee_dates CHECK (valid_to >= valid_from)
);

CREATE INDEX IF NOT EXISTS ix_service_fee_lookup
    ON golf.service_fee (golf_course_id, fee_type, valid_from, valid_to);


/* ---------------------------------------------------------------------
 * E-6. 라운드 (한 팀의 골프장 이용 1회)
 *      CHECKED_IN(체크인, 출발 대기) -> PLAYING(코스 사용 중)
 *      -> FINISHED(종료) / CANCELLED(취소)
 *      current_course_id: PLAYING 일 때 지금 사용 중인 코스
 *      settlement_status: 요금·수납 합계로 계산해 저장(UNPAID/PARTIAL/PAID)
 *      예약 시스템에서 온 팀은 reservation_id·tee_time_id 를 남긴다(워크인은 NULL).
 *      "round" 는 예약어가 아니지만 함수명과 겹치므로 항상 golf.round 로 쓴다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.round (
    round_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_no          VARCHAR(30),                           -- RD-yyyyMMdd-{id}, 저장 직후 채운다
    golf_course_id    BIGINT        NOT NULL,
    reservation_id    BIGINT,
    tee_time_id       BIGINT,
    play_date         DATE          NOT NULL,
    tee_off_time      TIME,                                  -- 예정 출발 시각
    planned_holes     SMALLINT      NOT NULL DEFAULT 18,
    round_status      VARCHAR(20)   NOT NULL DEFAULT 'CHECKED_IN',
    current_course_id BIGINT,
    checked_in_at     TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    started_at        TIMESTAMP(6),
    finished_at       TIMESTAMP(6),
    cancelled_at      TIMESTAMP(6),
    cancel_reason     VARCHAR(500),
    settlement_status VARCHAR(20)   NOT NULL DEFAULT 'UNPAID',
    memo              VARCHAR(500),
    created_by        BIGINT,
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at        TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_round PRIMARY KEY (round_id),
    CONSTRAINT uq_round_no UNIQUE (round_no),
    CONSTRAINT fk_round_golf_course    FOREIGN KEY (golf_course_id)    REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT fk_round_reservation    FOREIGN KEY (reservation_id)    REFERENCES golf.reservation (reservation_id),
    CONSTRAINT fk_round_tee_time       FOREIGN KEY (tee_time_id)       REFERENCES golf.tee_time (tee_time_id),
    CONSTRAINT fk_round_current_course FOREIGN KEY (current_course_id) REFERENCES golf.course (course_id),
    CONSTRAINT fk_round_created_by     FOREIGN KEY (created_by)        REFERENCES golf.admin_user (admin_user_id),
    CONSTRAINT ck_round_planned_holes CHECK (planned_holes IN (9, 18, 27, 36)),
    CONSTRAINT ck_round_status
        CHECK (round_status IN ('CHECKED_IN', 'PLAYING', 'FINISHED', 'CANCELLED')),
    CONSTRAINT ck_round_settlement_status
        CHECK (settlement_status IN ('UNPAID', 'PARTIAL', 'PAID')),
    CONSTRAINT ck_round_playing_course CHECK (round_status <> 'PLAYING' OR current_course_id IS NOT NULL),
    CONSTRAINT ck_round_started  CHECK (round_status NOT IN ('PLAYING', 'FINISHED') OR started_at IS NOT NULL),
    CONSTRAINT ck_round_finished CHECK (round_status <> 'FINISHED' OR finished_at IS NOT NULL),
    CONSTRAINT ck_round_cancelled CHECK (round_status <> 'CANCELLED' OR cancelled_at IS NOT NULL)
);

-- 예약 1건은 취소되지 않은 라운드 1개로만 체크인한다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_round_reservation
    ON golf.round (reservation_id)
    WHERE reservation_id IS NOT NULL AND round_status <> 'CANCELLED';
CREATE INDEX IF NOT EXISTS ix_round_course_date
    ON golf.round (golf_course_id, play_date, round_status);
CREATE INDEX IF NOT EXISTS ix_round_status
    ON golf.round (round_status, current_course_id);
CREATE INDEX IF NOT EXISTS ix_round_tee_time
    ON golf.round (tee_time_id);


/* ---------------------------------------------------------------------
 * E-7. 라운드 참가자 (회원 또는 비회원)
 *      checked_out_at 이 NULL 이면 아직 골프장 안에 있는 사람이다.
 *      한 회원은 동시에 두 라운드에 있을 수 없다(ux_round_player_active_member).
 *      total_* 는 score 를 저장할 때마다 다시 계산한다(목록·통계용).
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.round_player (
    round_player_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_id        BIGINT       NOT NULL,
    player_order    SMALLINT     NOT NULL,
    member_id       BIGINT,
    player_name     VARCHAR(100) NOT NULL,
    phone           VARCHAR(30),
    handicap        SMALLINT,
    locker_no       VARCHAR(10),
    checked_in_at   TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    checked_out_at  TIMESTAMP(6),
    holes_played    SMALLINT     NOT NULL DEFAULT 0,
    total_strokes   SMALLINT     NOT NULL DEFAULT 0,
    total_putts     SMALLINT     NOT NULL DEFAULT 0,
    par_played      SMALLINT     NOT NULL DEFAULT 0,         -- 친 홀들의 파 합계(타수 - 이 값 = 오버/언더)
    CONSTRAINT pk_round_player PRIMARY KEY (round_player_id),
    CONSTRAINT fk_round_player_round  FOREIGN KEY (round_id)  REFERENCES golf.round (round_id),
    CONSTRAINT fk_round_player_member FOREIGN KEY (member_id) REFERENCES golf.member (member_id),
    CONSTRAINT uq_round_player_order UNIQUE (round_id, player_order),
    CONSTRAINT ck_round_player_order CHECK (player_order BETWEEN 1 AND 8),
    CONSTRAINT ck_round_player_handicap CHECK (handicap IS NULL OR handicap BETWEEN 0 AND 54),
    CONSTRAINT ck_round_player_checkout CHECK (checked_out_at IS NULL OR checked_out_at >= checked_in_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_round_player_active_member
    ON golf.round_player (member_id)
    WHERE member_id IS NOT NULL AND checked_out_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_round_player_member
    ON golf.round_player (member_id, checked_in_at DESC);
CREATE INDEX IF NOT EXISTS ix_round_player_round
    ON golf.round_player (round_id);


/* ---------------------------------------------------------------------
 * E-8. 코스 사용 기록 (라운드가 어느 코스를 언제부터 언제까지 썼는지)
 *      18홀 = OUT -> IN 처럼 두 행이 생긴다. finished_at 이 NULL 인 행이
 *      지금 사용 중인 코스이며, 라운드당 하나만 열려 있을 수 있다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.round_course (
    round_course_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_id        BIGINT       NOT NULL,
    course_id       BIGINT       NOT NULL,
    seq_no          SMALLINT     NOT NULL,
    started_at      TIMESTAMP(6) NOT NULL,
    finished_at     TIMESTAMP(6),
    CONSTRAINT pk_round_course PRIMARY KEY (round_course_id),
    CONSTRAINT fk_round_course_round  FOREIGN KEY (round_id)  REFERENCES golf.round (round_id),
    CONSTRAINT fk_round_course_course FOREIGN KEY (course_id) REFERENCES golf.course (course_id),
    CONSTRAINT uq_round_course_seq UNIQUE (round_id, seq_no),
    CONSTRAINT ck_round_course_seq CHECK (seq_no BETWEEN 1 AND 4),
    CONSTRAINT ck_round_course_period CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_round_course_open
    ON golf.round_course (round_id)
    WHERE finished_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_round_course_course
    ON golf.round_course (course_id, started_at);


/* ---------------------------------------------------------------------
 * E-9. 캐디·카트 배정 이력
 *      released_at 이 NULL 이면 지금 배정 중이다.
 *      캐디 1명·카트 1대는 동시에 한 라운드에만 배정된다(부분 유니크 인덱스).
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.round_assignment (
    round_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_id            BIGINT       NOT NULL,
    resource_type       VARCHAR(10)  NOT NULL,
    caddie_id           BIGINT,
    cart_id             BIGINT,
    assigned_at         TIMESTAMP(6) NOT NULL,
    released_at         TIMESTAMP(6),
    assigned_by         BIGINT,
    release_reason      VARCHAR(200),
    CONSTRAINT pk_round_assignment PRIMARY KEY (round_assignment_id),
    CONSTRAINT fk_assignment_round  FOREIGN KEY (round_id)    REFERENCES golf.round (round_id),
    CONSTRAINT fk_assignment_caddie FOREIGN KEY (caddie_id)   REFERENCES golf.caddie (caddie_id),
    CONSTRAINT fk_assignment_cart   FOREIGN KEY (cart_id)     REFERENCES golf.cart (cart_id),
    CONSTRAINT fk_assignment_staff  FOREIGN KEY (assigned_by) REFERENCES golf.admin_user (admin_user_id),
    CONSTRAINT ck_assignment_resource CHECK (
        (resource_type = 'CADDIE' AND caddie_id IS NOT NULL AND cart_id IS NULL)
        OR (resource_type = 'CART' AND cart_id IS NOT NULL AND caddie_id IS NULL)),
    CONSTRAINT ck_assignment_period CHECK (released_at IS NULL OR released_at >= assigned_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_assignment_active_caddie
    ON golf.round_assignment (caddie_id)
    WHERE caddie_id IS NOT NULL AND released_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_assignment_active_cart
    ON golf.round_assignment (cart_id)
    WHERE cart_id IS NOT NULL AND released_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_assignment_round
    ON golf.round_assignment (round_id);
CREATE INDEX IF NOT EXISTS ix_assignment_caddie_history
    ON golf.round_assignment (caddie_id, assigned_at);


/* ---------------------------------------------------------------------
 * E-10. 홀별 스코어
 *       한 참가자가 한 코스 사용 구간(round_course)의 한 홀에 한 행.
 *       (36홀처럼 같은 코스를 두 번 돌아도 구간이 달라 구분된다)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.score (
    score_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_player_id BIGINT       NOT NULL,
    round_course_id BIGINT       NOT NULL,
    hole_id         BIGINT       NOT NULL,
    strokes         SMALLINT     NOT NULL,
    putts           SMALLINT,
    penalties       SMALLINT     NOT NULL DEFAULT 0,
    fairway_hit     BOOLEAN,
    recorded_by     BIGINT,
    recorded_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_score PRIMARY KEY (score_id),
    CONSTRAINT fk_score_player       FOREIGN KEY (round_player_id) REFERENCES golf.round_player (round_player_id),
    CONSTRAINT fk_score_round_course FOREIGN KEY (round_course_id) REFERENCES golf.round_course (round_course_id),
    CONSTRAINT fk_score_hole         FOREIGN KEY (hole_id)         REFERENCES golf.hole (hole_id),
    CONSTRAINT fk_score_recorded_by  FOREIGN KEY (recorded_by)     REFERENCES golf.admin_user (admin_user_id),
    CONSTRAINT uq_score_hole UNIQUE (round_player_id, round_course_id, hole_id),
    CONSTRAINT ck_score_strokes CHECK (strokes BETWEEN 1 AND 20),
    CONSTRAINT ck_score_putts CHECK (putts IS NULL OR (putts BETWEEN 0 AND 10 AND putts <= strokes)),
    CONSTRAINT ck_score_penalties CHECK (penalties BETWEEN 0 AND 10)
);

CREATE INDEX IF NOT EXISTS ix_score_round_course ON golf.score (round_course_id);


/* ---------------------------------------------------------------------
 * E-11. 라운드 이용 내역(타임라인)
 *       체크인·출발·코스 이동·배정·스코어·요금·수납·종료를 시간순으로 남긴다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.round_event (
    round_event_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_id            BIGINT        NOT NULL,
    event_type          VARCHAR(30)   NOT NULL,
    course_id           BIGINT,
    round_player_id     BIGINT,
    message             VARCHAR(1000),
    actor_admin_user_id BIGINT,
    occurred_at         TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_round_event PRIMARY KEY (round_event_id),
    CONSTRAINT fk_round_event_round  FOREIGN KEY (round_id)            REFERENCES golf.round (round_id),
    CONSTRAINT fk_round_event_course FOREIGN KEY (course_id)           REFERENCES golf.course (course_id),
    CONSTRAINT fk_round_event_player FOREIGN KEY (round_player_id)     REFERENCES golf.round_player (round_player_id),
    CONSTRAINT fk_round_event_actor  FOREIGN KEY (actor_admin_user_id) REFERENCES golf.admin_user (admin_user_id),
    CONSTRAINT ck_round_event_type CHECK (event_type IN (
        'CHECK_IN', 'PLAYER_ADDED', 'PLAYER_REMOVED', 'START', 'COURSE_CHANGED',
        'CADDIE_ASSIGNED', 'CADDIE_RELEASED', 'CART_ASSIGNED', 'CART_RELEASED',
        'SCORE_RECORDED', 'CHARGE_ADDED', 'CHARGE_VOIDED', 'PAYMENT_RECEIVED',
        'PAYMENT_CANCELLED', 'FINISH', 'CANCEL'))
);

CREATE INDEX IF NOT EXISTS ix_round_event_round ON golf.round_event (round_id, occurred_at);


/* ---------------------------------------------------------------------
 * E-12. 라운드 요금 (그린피·캐디피·카트비 등)
 *       round_player_id NULL = 팀 공통 요금
 *       취소는 지우지 않고 is_void 로 표시한다.
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.round_charge (
    round_charge_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    round_id        BIGINT        NOT NULL,
    round_player_id BIGINT,
    charge_type     VARCHAR(20)   NOT NULL,
    description     VARCHAR(200),
    unit_price      NUMERIC(12,2) NOT NULL,
    quantity        SMALLINT      NOT NULL DEFAULT 1,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    amount          NUMERIC(12,2) NOT NULL,
    is_void         BOOLEAN       NOT NULL DEFAULT FALSE,
    voided_at       TIMESTAMP(6),
    void_reason     VARCHAR(200),
    created_by      BIGINT,
    created_at      TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_round_charge PRIMARY KEY (round_charge_id),
    CONSTRAINT fk_round_charge_round  FOREIGN KEY (round_id)        REFERENCES golf.round (round_id),
    CONSTRAINT fk_round_charge_player FOREIGN KEY (round_player_id) REFERENCES golf.round_player (round_player_id),
