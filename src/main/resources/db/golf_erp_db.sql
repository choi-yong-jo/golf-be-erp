    CONSTRAINT ck_rental_payment_method CHECK (
        payment_method IN ('CASH','CARD','BANK_TRANSFER','KAKAO_PAY','NAVER_PAY','ETC')),
    CONSTRAINT ck_rental_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_rental_payment_status CHECK (payment_status IN ('PAID','CANCELLED','REFUNDED'))
);
CREATE INDEX IF NOT EXISTS ix_equipment_rental_payment
    ON golf.equipment_rental_payment(equipment_rental_id, paid_at);

CREATE TABLE IF NOT EXISTS golf.equipment_rental_history (
