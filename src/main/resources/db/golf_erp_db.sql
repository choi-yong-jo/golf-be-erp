    stock_txn_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_equipment_id BIGINT NOT NULL REFERENCES golf.rental_equipment(rental_equipment_id),
    golf_course_id BIGINT NOT NULL REFERENCES golf.golf_course(golf_course_id),
    transaction_type VARCHAR(20) NOT NULL,
    quantity INTEGER NOT NULL,
    reference_type VARCHAR(30),
    reference_id BIGINT,
    reason VARCHAR(500),
    actor_admin_user_id BIGINT REFERENCES golf.admin_user(admin_user_id),
    occurred_at TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
