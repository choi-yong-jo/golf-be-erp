        transaction_type IN ('STOCK_IN','RENT_OUT','RETURN','MAINTENANCE_OUT','MAINTENANCE_IN','LOSS','ADJUSTMENT')),
    CONSTRAINT ck_rental_stock_txn_quantity CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS ix_rental_stock_txn_item_date
    ON golf.rental_equipment_stock_txn(rental_equipment_id, golf_course_id, occurred_at);

CREATE TABLE IF NOT EXISTS golf.equipment_rental (
    equipment_rental_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_no VARCHAR(40) NOT NULL UNIQUE,
    golf_course_id BIGINT NOT NULL REFERENCES golf.golf_course(golf_course_id),
    reservation_id BIGINT REFERENCES golf.reservation(reservation_id),
    round_id BIGINT REFERENCES golf.round(round_id),
    member_id BIGINT REFERENCES golf.member(member_id),
    renter_name VARCHAR(100) NOT NULL,
    renter_phone VARCHAR(30),
    rental_status VARCHAR(20) NOT NULL DEFAULT 'RESERVED',
    rented_at TIMESTAMP(6),
    due_at TIMESTAMP(6),
    returned_at TIMESTAMP(6),
    rental_fee_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    deposit_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    damage_fee_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    received_by BIGINT REFERENCES golf.admin_user(admin_user_id),
    returned_to BIGINT REFERENCES golf.admin_user(admin_user_id),
    memo VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT ck_equipment_rental_status CHECK (
        rental_status IN ('RESERVED','RENTED','PARTIALLY_RETURNED','RETURNED','CANCELLED','OVERDUE')),
    CONSTRAINT ck_equipment_rental_dates CHECK (
        due_at IS NULL OR rented_at IS NULL OR due_at >= rented_at),
    CONSTRAINT ck_equipment_rental_amounts CHECK (
        rental_fee_total >= 0 AND deposit_total >= 0 AND damage_fee_total >= 0)
);
CREATE INDEX IF NOT EXISTS ix_equipment_rental_status_due
    ON golf.equipment_rental(golf_course_id, rental_status, due_at);
CREATE INDEX IF NOT EXISTS ix_equipment_rental_member
    ON golf.equipment_rental(member_id, created_at DESC);

CREATE TABLE IF NOT EXISTS golf.equipment_rental_item (
    equipment_rental_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_rental_id BIGINT NOT NULL REFERENCES golf.equipment_rental(equipment_rental_id) ON DELETE CASCADE,
    rental_equipment_id BIGINT NOT NULL REFERENCES golf.rental_equipment(rental_equipment_id),
    equipment_id BIGINT REFERENCES golf.equipment(equipment_id),
    quantity INTEGER NOT NULL DEFAULT 1,
    returned_quantity INTEGER NOT NULL DEFAULT 0,
    daily_rental_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
    rental_days INTEGER NOT NULL DEFAULT 1,
    deposit_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    damage_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
    item_status VARCHAR(20) NOT NULL DEFAULT 'RENTED',
    condition_out VARCHAR(500),
    condition_in VARCHAR(500),
    returned_at TIMESTAMP(6),
    CONSTRAINT ck_rental_item_quantity CHECK (
        quantity > 0 AND returned_quantity >= 0 AND returned_quantity <= quantity),
    CONSTRAINT ck_rental_item_amount CHECK (
        daily_rental_fee >= 0 AND rental_days > 0 AND deposit_amount >= 0 AND damage_fee >= 0),
    CONSTRAINT ck_rental_item_status CHECK (
        item_status IN ('RESERVED','RENTED','PARTIALLY_RETURNED','RETURNED','LOST','DAMAGED','CANCELLED'))
);
CREATE INDEX IF NOT EXISTS ix_equipment_rental_item_parent
    ON golf.equipment_rental_item(equipment_rental_id);

CREATE TABLE IF NOT EXISTS golf.equipment_rental_payment (
    rental_payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_rental_id BIGINT NOT NULL REFERENCES golf.equipment_rental(equipment_rental_id),
    payment_type VARCHAR(20) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
