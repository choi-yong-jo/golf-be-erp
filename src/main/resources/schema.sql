-- =====================================================================
-- 골프장 예약 시스템 통합 스키마 (PostgreSQL, schema: golf)
--
--   E: golf-be-erp 기존 DDL (members, golf_courses, reservations,
--      fee_policies, payments, settlements, users, audit_logs)
--   M: 이전 통합 스키마 (E + tee_times 등)
--   G: golf 스키마     (member, golf_course, green_fee_policy, tee_time,
--      reservation, reservation_player, reservation_history,
--      golf_course_closure, payment, reservation_restriction)
--
-- 구성
--   1부. 실제 테이블: M + G 통합 규칙(아래)에 따라 만든 단수형 테이블.
--        E 의 모든 컬럼은 이 테이블들에 이미 포함되어 있다.
--   2부. 호환 뷰: E 의 테이블명/컬럼명(members.id, golf_courses.name ...)
--        그대로 조회·INSERT·UPDATE·DELETE 할 수 있는 자동 갱신 뷰.
--        golf-be-erp 의 JPA 엔티티와 MyBatis 매퍼를 고치지 않아도 동작한다.
--
-- 통합 원칙
--   1. 명명 규칙은 G 를 따른다: 단수형 테이블명, PK 는 <테이블>_id,
--      의미가 겹치는 컬럼은 접두어를 붙인 G 의 이름(member_name 등).
--   2. 같은 테이블은 양쪽 컬럼을 모두 포함(합집합)한다.
--      이름만 다르고 의미가 같은 컬럼은 G 의 이름으로 하나로 합친다.
--   3. 한쪽에만 있는 컬럼은 NULL 허용 또는 DEFAULT 를 두어
--      다른 쪽 애플리케이션의 INSERT 가 실패하지 않게 한다.
--   4. 길이·정밀도·정수 타입이 다르면 더 넓은 쪽을 택한다. (E.JSON -> JSONB)
--   5. 상태값 CHECK 는 양쪽 값의 합집합으로 만든다.
--   6. 시각 기본값은 LOCALTIMESTAMP, 정밀도는 TIMESTAMP(6) 으로 맞춘다.
--
-- 실행
--   - 모든 문장이 IF NOT EXISTS / CREATE OR REPLACE 라 여러 번 실행해도 안전하다.
--   - Spring sql.init 으로도 돌 수 있게 BEGIN/COMMIT, SET search_path 는 넣지 않았다.
--     psql 로 한 트랜잭션에 실행하려면: psql -1 -d golf -f schema.sql
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS golf;

SET search_path TO golf;

BEGIN;

-- #####################################################################
-- 1부. 테이블
-- #####################################################################

/* ---------------------------------------------------------------------
 * 1. 회원 (E.members + G.member)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.member (
    member_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_no     VARCHAR(30),                                 -- [E] 회원번호
    login_id      VARCHAR(100),                                -- [G] 오프라인 회원 위해 NULL 허용
    password_hash VARCHAR(255),                                -- BCrypt, 오프라인 회원은 NULL
    member_name   VARCHAR(100) NOT NULL,                       -- E.name
    phone         VARCHAR(30),
    email         VARCHAR(255),                                -- 소문자로 정규화해 저장
    role          VARCHAR(10)  NOT NULL DEFAULT 'USER',
    member_status VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',      -- E.status
    created_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_member PRIMARY KEY (member_id),
    CONSTRAINT uq_member_login_id  UNIQUE (login_id),          -- NULL 은 중복 허용
    CONSTRAINT uq_member_member_no UNIQUE (member_no),
    CONSTRAINT uq_member_email     UNIQUE (email),
    CONSTRAINT ck_member_role   CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_member_status CHECK (member_status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE INDEX IF NOT EXISTS ix_member_name  ON golf.member (member_name);
CREATE INDEX IF NOT EXISTS ix_member_phone ON golf.member (phone);


/* ---------------------------------------------------------------------
 * 2. 관리자/직원 계정 (E.users)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.admin_user (
    admin_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(60)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    role          VARCHAR(30)  NOT NULL DEFAULT 'STAFF',
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,          -- E.active
    created_at    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_admin_user PRIMARY KEY (admin_user_id),
    CONSTRAINT uq_admin_user_username UNIQUE (username)
);


/* ---------------------------------------------------------------------
 * 3. 골프장 (E.golf_courses + G.golf_course)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.golf_course (
    golf_course_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    course_code    VARCHAR(30)  NOT NULL,
    course_name    VARCHAR(200) NOT NULL,                      -- E.name
    address        VARCHAR(500),                               -- [G]
    phone          VARCHAR(30),                                -- [G]
    hole_count     INTEGER      DEFAULT 18,
    course_status  VARCHAR(20)  NOT NULL DEFAULT 'OPEN',       -- E.status
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,         -- [G]
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_golf_course PRIMARY KEY (golf_course_id),
    CONSTRAINT uq_golf_course_code UNIQUE (course_code)
);


/* ---------------------------------------------------------------------
 * 4. 골프장 휴장 관리 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.golf_course_closure (
    closure_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id BIGINT       NOT NULL,
    closure_start  TIMESTAMP(6) NOT NULL,                      -- 포함
    closure_end    TIMESTAMP(6) NOT NULL,                      -- 미포함
    closure_type   VARCHAR(20)  NOT NULL DEFAULT 'CLOSED',
    reason         VARCHAR(500) NOT NULL,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_golf_course_closure PRIMARY KEY (closure_id),
    CONSTRAINT fk_closure_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_closure_period CHECK (closure_end > closure_start)
);

CREATE INDEX IF NOT EXISTS ix_closure_course_period
    ON golf.golf_course_closure (golf_course_id, closure_start, closure_end);


/* ---------------------------------------------------------------------
 * 5. 그린피 요금 정책 (E.fee_policies + G.green_fee_policy)
 *    golf_course_id NULL = 전체 골프장, 유효기간 기본값 = 무기한
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.green_fee_policy (
    green_fee_policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id      BIGINT,
    policy_name         VARCHAR(150)  NOT NULL,                -- E.name
    valid_from          DATE          NOT NULL DEFAULT CURRENT_DATE,
    valid_to            DATE          NOT NULL DEFAULT DATE '9999-12-31',
    day_type            VARCHAR(20),                           -- [E] WEEKDAY, WEEKEND, HOLIDAY
    day_of_week         SMALLINT,                              -- [G] 1(월)~7(일), NULL 이면 모든 요일
    time_from           TIME,                                  -- E.start_time, 포함
    time_to             TIME,                                  -- E.end_time, 미포함
    base_fee            NUMERIC(12,2) NOT NULL,                -- E.amount
    discount_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE,   -- E.active
    created_at          TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_green_fee_policy PRIMARY KEY (green_fee_policy_id),
    CONSTRAINT fk_green_fee_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_green_fee_dates CHECK (valid_to >= valid_from),
    CONSTRAINT ck_green_fee_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_green_fee_amount
        CHECK (base_fee >= 0 AND discount_amount >= 0 AND discount_amount <= base_fee)
);

CREATE INDEX IF NOT EXISTS ix_green_fee_course_valid
    ON golf.green_fee_policy (golf_course_id, valid_from, valid_to);


/* ---------------------------------------------------------------------
 * 6. 티타임 (M.tee_times + G.tee_time)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.tee_time (
    tee_time_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    golf_course_id  BIGINT,
    course          VARCHAR(20),                               -- [M] 세부 코스, 예: OUT, IN
    play_date       DATE          NOT NULL,
    start_time      TIME          NOT NULL,
    hole_type       VARCHAR(10)   NOT NULL DEFAULT '18H',      -- [G]
    capacity        SMALLINT      NOT NULL DEFAULT 4,          -- [G]
    green_fee       NUMERIC(12,2),                             -- [M] 1인 그린피(원)
    tee_time_status VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    version         BIGINT        NOT NULL DEFAULT 0,          -- [M] @Version
    CONSTRAINT pk_tee_time PRIMARY KEY (tee_time_id),
    CONSTRAINT fk_tee_time_course FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_tee_time_slot CHECK (golf_course_id IS NOT NULL OR course IS NOT NULL),
    CONSTRAINT ck_tee_time_capacity CHECK (capacity BETWEEN 1 AND 8),
    CONSTRAINT ck_tee_time_status
        CHECK (tee_time_status IN ('OPEN', 'BOOKED', 'BLOCKED', 'CLOSED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_tee_time_slot
    ON golf.tee_time (COALESCE(golf_course_id, 0), play_date, start_time, COALESCE(course, ''));
CREATE INDEX IF NOT EXISTS ix_tee_time_search
    ON golf.tee_time (golf_course_id, play_date, tee_time_status, start_time);
CREATE INDEX IF NOT EXISTS ix_tee_time_play_date
    ON golf.tee_time (play_date, start_time);


/* ---------------------------------------------------------------------
 * 7. 예약 (E.reservations + G.reservation)
 *    reserved_at 의미 차이 주의
 *      G.reserved_at = 예약한 시각 -> reserved_at
 *      E.reserved_at = 플레이 일시 -> play_at
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation (
    reservation_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_no     VARCHAR(30),
    member_id          BIGINT        NOT NULL,
    tee_time_id        BIGINT,
    golf_course_id     BIGINT,                                 -- E.course_id
    play_at            TIMESTAMP(6),                           -- E.reserved_at (플레이 일시)
    reservation_status VARCHAR(20)   NOT NULL DEFAULT 'PENDING', -- E.status
    player_count       INTEGER       NOT NULL DEFAULT 4,
    green_fee_amount   NUMERIC(12,2),
    discount_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_amount       NUMERIC(12,2),
    memo               VARCHAR(500),                           -- [E]
    reserved_at        TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP, -- [G] 예약한 시각
    created_at         TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at         TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    payment_started_at TIMESTAMP(6),
    confirmed_at       TIMESTAMP(6),
    cancelled_at       TIMESTAMP(6),
    cancel_reason      VARCHAR(500),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),
    CONSTRAINT uq_reservation_no UNIQUE (reservation_no),
    CONSTRAINT fk_reservation_member   FOREIGN KEY (member_id)      REFERENCES golf.member (member_id),
    CONSTRAINT fk_reservation_tee_time FOREIGN KEY (tee_time_id)    REFERENCES golf.tee_time (tee_time_id),
    CONSTRAINT fk_reservation_course   FOREIGN KEY (golf_course_id) REFERENCES golf.golf_course (golf_course_id),
    CONSTRAINT ck_reservation_slot
        CHECK (tee_time_id IS NOT NULL OR (golf_course_id IS NOT NULL AND play_at IS NOT NULL)),
    CONSTRAINT ck_reservation_player_count CHECK (player_count BETWEEN 1 AND 8),
    CONSTRAINT ck_reservation_status
        CHECK (reservation_status IN (
            'PENDING', 'PENDING_PAYMENT', 'PAYING', 'CONFIRMED', 'REFUND_PENDING',
            'CANCELLED', 'COMPLETED', 'NO_SHOW', 'FAILED')),
    CONSTRAINT ck_reservation_amount
        CHECK (green_fee_amount >= 0
               AND discount_amount >= 0
               AND total_amount >= 0
               AND discount_amount <= green_fee_amount)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_reservation_active_tee_time
    ON golf.reservation (tee_time_id)
    WHERE reservation_status IN ('PENDING', 'PENDING_PAYMENT', 'PAYING', 'CONFIRMED');
CREATE INDEX IF NOT EXISTS ix_reservation_member
    ON golf.reservation (member_id, reserved_at DESC);
CREATE INDEX IF NOT EXISTS ix_reservation_member_status
    ON golf.reservation (member_id, reservation_status);
CREATE INDEX IF NOT EXISTS ix_reservation_tee_time
    ON golf.reservation (tee_time_id);
CREATE INDEX IF NOT EXISTS ix_reservation_course
    ON golf.reservation (golf_course_id);
CREATE INDEX IF NOT EXISTS ix_reservation_play_at                 -- E.idx_res_reserved_at
    ON golf.reservation (play_at);
CREATE INDEX IF NOT EXISTS ix_reservation_status_play_at          -- E.idx_res_status_reserved
    ON golf.reservation (reservation_status, play_at);
CREATE INDEX IF NOT EXISTS ix_reservation_status_created
    ON golf.reservation (reservation_status, created_at);
CREATE INDEX IF NOT EXISTS ix_reservation_status_payment_started
    ON golf.reservation (reservation_status, payment_started_at);


/* ---------------------------------------------------------------------
 * 8. 예약자 및 동반자 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation_player (
    reservation_player_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id        BIGINT       NOT NULL,
    player_order          SMALLINT     NOT NULL,
    player_name           VARCHAR(100) NOT NULL,
    phone                 VARCHAR(30),
    member_id             BIGINT,
    is_booking_member     BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_reservation_player PRIMARY KEY (reservation_player_id),
    CONSTRAINT fk_player_reservation FOREIGN KEY (reservation_id) REFERENCES golf.reservation (reservation_id),
    CONSTRAINT fk_player_member      FOREIGN KEY (member_id)      REFERENCES golf.member (member_id),
    CONSTRAINT uq_player_order UNIQUE (reservation_id, player_order)
);

CREATE INDEX IF NOT EXISTS ix_player_member ON golf.reservation_player (member_id);


/* ---------------------------------------------------------------------
 * 9. 예약 변경 이력 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation_history (
    reservation_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id         BIGINT        NOT NULL,
    action_type            VARCHAR(30)   NOT NULL,
    before_status          VARCHAR(20),
    after_status           VARCHAR(20),
    before_tee_time_id     BIGINT,
    after_tee_time_id      BIGINT,
    before_amount          NUMERIC(12,2),
    after_amount           NUMERIC(12,2),
    reason                 VARCHAR(1000),
    actor_member_id        BIGINT,
    created_at             TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_reservation_history PRIMARY KEY (reservation_history_id),
    CONSTRAINT fk_history_reservation FOREIGN KEY (reservation_id)  REFERENCES golf.reservation (reservation_id),
    CONSTRAINT fk_history_actor       FOREIGN KEY (actor_member_id) REFERENCES golf.member (member_id)
);

CREATE INDEX IF NOT EXISTS ix_history_reservation
    ON golf.reservation_history (reservation_id, created_at);


/* ---------------------------------------------------------------------
 * 10. 회원별 예약 제한 (G 전용)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.reservation_restriction (
    restriction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_id        BIGINT        NOT NULL,
    restriction_type VARCHAR(30)   NOT NULL,
    starts_at        TIMESTAMP(6)  NOT NULL,
    ends_at          TIMESTAMP(6),                             -- NULL 이면 무기한
    reason           VARCHAR(1000) NOT NULL,
    created_by       BIGINT,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_reservation_restriction PRIMARY KEY (restriction_id),
    CONSTRAINT fk_restriction_member FOREIGN KEY (member_id) REFERENCES golf.member (member_id),
    CONSTRAINT ck_restriction_period CHECK (ends_at IS NULL OR ends_at > starts_at)
);

CREATE INDEX IF NOT EXISTS ix_restriction_member
    ON golf.reservation_restriction (member_id, starts_at);


/* ---------------------------------------------------------------------
 * 11. 결제 및 환불 (E.payments + G.payment)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.payment (
    payment_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id    BIGINT        NOT NULL,
    payment_type      VARCHAR(20)   NOT NULL DEFAULT 'PAYMENT', -- [G]
    payment_status    VARCHAR(20)   NOT NULL DEFAULT 'READY',   -- E.status
    payment_method    VARCHAR(30),
    pg_provider       VARCHAR(50),
    pg_transaction_id VARCHAR(200),
    amount            NUMERIC(12,2) NOT NULL,
    requested_at      TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP, -- E.created_at
    completed_at      TIMESTAMP(6),                             -- E.paid_at
    refunded_at       TIMESTAMP(6),
    failure_reason    VARCHAR(500),
    CONSTRAINT pk_payment PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_reservation FOREIGN KEY (reservation_id) REFERENCES golf.reservation (reservation_id),
    CONSTRAINT ck_payment_type CHECK (payment_type IN ('PAYMENT', 'REFUND')),
    CONSTRAINT ck_payment_status
        CHECK (payment_status IN (
            'READY', 'PENDING', 'SUCCEEDED', 'PAID',
            'FAILED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_paid
        CHECK (payment_status <> 'PAID' OR (completed_at IS NOT NULL AND pg_transaction_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ix_payment_reservation
    ON golf.payment (reservation_id, payment_type);


/* ---------------------------------------------------------------------
 * 12. 일별 정산 (E.settlements)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.settlement (
    settlement_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    settlement_date   DATE          NOT NULL,
    gross_amount      NUMERIC(14,2) NOT NULL DEFAULT 0,
    refund_amount     NUMERIC(14,2) NOT NULL DEFAULT 0,
    net_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    settlement_status VARCHAR(20)   NOT NULL DEFAULT 'OPEN',   -- E.status
    created_at        TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_settlement PRIMARY KEY (settlement_id),
    CONSTRAINT uq_settlement_date UNIQUE (settlement_date)
);


/* ---------------------------------------------------------------------
 * 13. 감사 로그 (E.audit_logs)
 * ------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS golf.audit_log (
    audit_log_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_username VARCHAR(60),
    action         VARCHAR(80)  NOT NULL,
    entity_type    VARCHAR(80)  NOT NULL,
    entity_id      BIGINT,
    details        JSONB,                                      -- E.JSON -> JSONB
    created_at     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_log_id)
);

CREATE INDEX IF NOT EXISTS ix_audit_log_entity ON golf.audit_log (entity_type, entity_id);


-- #####################################################################
-- 2부. golf-be-erp 호환 뷰 (E 의 테이블명·컬럼명 그대로)
--   - 단일 테이블 + 컬럼 이름 변경만 하므로 PostgreSQL 자동 갱신 뷰다.
--     INSERT/UPDATE/DELETE 와 INSERT ... RETURNING 이 그대로 된다.
--   - 뷰에 없는 컬럼은 원본 테이블의 DEFAULT(IDENTITY 포함)가 적용된다.
--   - 엔티티/매퍼를 새 테이블명으로 옮긴 뒤에는 이 부분을 지워도 된다.
-- #####################################################################

CREATE OR REPLACE VIEW golf.members AS
SELECT member_id     AS id,
       member_no,
       member_name   AS name,
       phone,
       email,
       member_status AS status,
       created_at,
       updated_at
  FROM golf.member;

CREATE OR REPLACE VIEW golf.golf_courses AS
SELECT golf_course_id AS id,
       course_code,
       course_name    AS name,
       hole_count,
       course_status  AS status,
       created_at,
       updated_at
  FROM golf.golf_course;

CREATE OR REPLACE VIEW golf.reservations AS
SELECT reservation_id     AS id,
       reservation_no,
       member_id,
       golf_course_id     AS course_id,
       play_at            AS reserved_at,      -- E 의 reserved_at = 플레이 일시
       player_count,
       reservation_status AS status,
       memo,
       created_at,
       updated_at
  FROM golf.reservation;

CREATE OR REPLACE VIEW golf.fee_policies AS
SELECT green_fee_policy_id AS id,
       policy_name         AS name,
       day_type,
       time_from           AS start_time,
       time_to             AS end_time,
       base_fee            AS amount,
       is_active           AS active,
       created_at
  FROM golf.green_fee_policy;

CREATE OR REPLACE VIEW golf.payments AS
SELECT payment_id     AS id,
       reservation_id,
       amount,
       payment_status AS status,
       completed_at   AS paid_at,
       payment_method,
       requested_at   AS created_at
  FROM golf.payment;

CREATE OR REPLACE VIEW golf.settlements AS
SELECT settlement_id     AS id,
       settlement_date,
       gross_amount,
       refund_amount,
       net_amount,
       settlement_status AS status,
       created_at
  FROM golf.settlement;

CREATE OR REPLACE VIEW golf.users AS
SELECT admin_user_id AS id,
       username,
       password_hash,
       display_name,
       role,
       is_active     AS active,
       created_at
  FROM golf.admin_user;

CREATE OR REPLACE VIEW golf.audit_logs AS
SELECT audit_log_id AS id,
       actor_username,
       action,
       entity_type,
       entity_id,
       details,
       created_at
  FROM golf.audit_log;

COMMIT;